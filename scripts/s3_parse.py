"""Etapa 3: parseo con tree-sitter de funciones y métodos.

Por repo (en paralelo) se escribe un shard en data/<modo>/s3_shards/; después se agregan, excluyendo
archivos idénticos que aparecen en >= N repos (templates).
Se excluyen: vendor/site-packages/migrations/tests/fixtures/docs/examples, archivos de test,
código autogenerado (protobuf, clientes OpenAPI/Swagger, "DO NOT EDIT", manage/wsgi/asgi.py de Django),
modelos copiados de HF (modeling_*.py, ...), funciones anidadas dentro
de otras funciones y funciones con menos de min_nonblank_lines líneas no vacías.
Salidas: data/<modo>/s3_functions.parquet, data/<modo>/s3_repos.parquet
Uso: uv run scripts/s3_parse.py [--mode pilot|full] [--force]
"""
import hashlib
import json
import os
import re
import shutil
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import pandas as pd
import tree_sitter_python as tsp
from tree_sitter import Language, Parser

from common import load_config, out_dir, stage

cfg = load_config()
P = cfg["parse"]
OUT = out_dir(cfg)
DST, REPOS = OUT / "s3_functions.parquet", OUT / "s3_repos.parquet"
SHARDS = OUT / "s3_shards"

EXCL_DIRS = {"vendor", "vendored", "_vendor", "third_party", "thirdparty", "site-packages", "node_modules",
             "venv", ".venv", "env", ".env", "virtualenv", "migrations", "alembic", "tests", "test", "testing",
             "fixtures", "__pycache__", "build", "dist", "docs", "doc", "examples", "example", ".git",
             "openapi_client", "swagger_client", "generated", "gen", "proto", "protos"}
TEST_FILE = re.compile(r"(^test_.*|.*_tests?\.py$|^tests?\.py$|^conftest\.py$)")
GEN_FILE = re.compile(r"(_pb2(_grpc)?\.py$|_pb2\.pyi$)")
# Scaffolding generado por django-admin startproject y archivos de modelos copiados de HF transformers
SCAFFOLD_FILE = re.compile(r"^(manage|wsgi|asgi)\.py$")
VENDORED_HF = re.compile(r"^(modeling|configuration|tokenization|processing|image_processing)_\w+\.py$")
GEN_MARK = re.compile(r"(generated by|auto-?generated|do not edit|openapi generator|swagger.codegen|"
                      r"code generated|autogenerated by)", re.I)
MAX_FILE_BYTES = 500_000


def file_kind(rel: str, head: str) -> str:
    parts = rel.split("/")
    if any(p.lower() in EXCL_DIRS for p in parts[:-1]):
        return "dir_excluido"
    name = parts[-1]
    if TEST_FILE.match(name):
        return "test"
    if GEN_FILE.search(name) or GEN_MARK.search(head) or SCAFFOLD_FILE.match(name):
        return "autogenerado"
    if VENDORED_HF.match(name):
        return "vendorizado_hf"
    return "ok"


def norm_hash(src: str) -> str:
    return hashlib.sha1(re.sub(r"\s+", "", src).encode()).hexdigest()


def parse_repo(job: dict) -> dict:
    parser = Parser(Language(tsp.language()))
    root, repo, sha = Path(job["path"]), job["repo"], job["sha"]
    files, funcs, counts = [], [], {}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        for fn in filenames:
            if not fn.endswith(".py"):
                continue
            fp = Path(dirpath) / fn
            rel = fp.relative_to(root).as_posix()
            try:
                raw = fp.read_bytes()
            except OSError:
                continue
            if len(raw) > MAX_FILE_BYTES:
                kind = "muy_grande"
            else:
                src = raw.decode("utf-8", "replace")
                kind = file_kind(rel, src[:2000])
            nonblank = sum(1 for l in raw.splitlines() if l.strip())
            counts[kind] = counts.get(kind, 0) + 1
            if kind != "ok":
                files.append({"path": rel, "kind": kind, "hash": None, "nonblank": nonblank})
                continue
            fh = norm_hash(src)
            files.append({"path": rel, "kind": kind, "hash": fh, "nonblank": nonblank})
            tree = parser.parse(raw)
            lines = raw.split(b"\n")
            stack = [(tree.root_node, [], False)]
            while stack:
                node, scope, in_func = stack.pop()
                for ch in node.children:
                    if ch.type == "class_definition":
                        nm = ch.child_by_field_name("name").text.decode()
                        stack.append((ch, scope + [nm], in_func))
                    elif ch.type == "decorated_definition":
                        stack.append((ch, scope, in_func))
                    elif ch.type == "function_definition":
                        nm = ch.child_by_field_name("name").text.decode()
                        if in_func:
                            counts["fn_anidada"] = counts.get("fn_anidada", 0) + 1
                            continue
                        stack.append((ch, scope + [nm], True))
                        s, e = ch.start_point[0], ch.end_point[0]
                        body = b"\n".join(lines[s:e + 1]).decode("utf-8", "replace")
                        nb = sum(1 for l in body.splitlines() if l.strip())
                        if nb < P["min_nonblank_lines"]:
                            counts["fn_corta"] = counts.get("fn_corta", 0) + 1
                            continue
                        funcs.append({
                            "fid": hashlib.sha1(f"{repo}:{rel}:{s}".encode()).hexdigest()[:16],
                            "repo": repo, "owner": job["owner"], "domain": job["domain"], "path": rel,
                            "qualname": ".".join(scope + [nm]), "name": nm, "start": s + 1, "end": e + 1,
                            "nonblank": nb, "is_method": bool(scope) and not in_func, "file_hash": fh,
                            "url": f"https://github.com/{repo}/blob/{sha}/{rel}#L{s + 1}-L{e + 1}",
                            "code": body})
                    elif ch.type in ("block", "if_statement", "try_statement", "with_statement",
                                     "else_clause", "except_clause", "finally_clause", "elif_clause"):
                        stack.append((ch, scope, in_func))
    shard = SHARDS / (repo.replace("/", "__") + ".parquet")
    pd.DataFrame(funcs).to_parquet(shard)
    meta = {"repo": repo, "files": files, "counts": counts}
    shard.with_suffix(".json").write_text(json.dumps(meta))
    return meta


if __name__ == "__main__":
    if DST.exists() and not cfg["force"]:
        print(f"ya existe {DST}; usar --force para rehacer")
        raise SystemExit
    if cfg["force"]:
        shutil.rmtree(SHARDS, ignore_errors=True)
    SHARDS.mkdir(exist_ok=True)
    dl = pd.read_parquet(OUT / "s2_downloads.parquet")
    dl = dl[dl.status.isin(["ok", "cacheado"])]
    with stage(cfg, "s3_parse", [DST, REPOS]) as st:
        jobs = [r._asdict() for r in dl.itertuples()]
        shard_meta = lambda j: SHARDS / (j["repo"].replace("/", "__") + ".json")
        todo = [j for j in jobs if not shard_meta(j).exists()]
        metas = [json.loads(shard_meta(j).read_text()) for j in jobs if shard_meta(j).exists()]
        with ProcessPoolExecutor(P["workers"]) as ex:
            for i, m in enumerate(ex.map(parse_repo, todo, chunksize=2), 1):
                metas.append(m)
                if i % 50 == 0:
                    print(f"  {i}/{len(todo)}")

        # Templates: hash de archivo normalizado presente en >= N repos distintos
        hash_repos = {}
        for m in metas:
            for f in m["files"]:
                if f["hash"]:
                    hash_repos.setdefault(f["hash"], set()).add(m["repo"])
        templates = {h for h, rs in hash_repos.items() if len(rs) >= P["template_file_min_repos"]}

        parts, n_fn_total, n_fn_template = [], 0, 0
        for j in jobs:
            df = pd.read_parquet(SHARDS / (j["repo"].replace("/", "__") + ".parquet"))
            n_fn_total += len(df)
            if len(df):
                mask = df.file_hash.isin(templates)
                n_fn_template += int(mask.sum())
                parts.append(df[~mask])
        funcs = pd.concat(parts, ignore_index=True)
        funcs.to_parquet(DST)

        repo_rows = []
        for m in metas:
            ok = [f for f in m["files"] if f["kind"] == "ok" and f["hash"] not in templates]
            repo_rows.append({"repo": m["repo"], "py_files": len(m["files"]), "py_files_ok": len(ok),
                              "py_nonblank_all": sum(f["nonblank"] for f in m["files"]),
                              "py_nonblank_ok": sum(f["nonblank"] for f in ok)})
        rdf = pd.DataFrame(repo_rows).merge(funcs.groupby("repo").size().rename("functions").reset_index(),
                                            on="repo", how="left").fillna({"functions": 0})
        rdf.to_parquet(REPOS)

        F = st["funnel"]
        F["repos_parseados"] = len(metas)
        tot = {}
        for m in metas:
            for k, v in m["counts"].items():
                tot[k] = tot.get(k, 0) + v
        F["archivos_py"] = sum(len(m["files"]) for m in metas)
        for k in ("dir_excluido", "test", "autogenerado", "vendorizado_hf", "muy_grande"):
            F[f"  archivos_excluidos:{k}"] = tot.get(k, 0)
        F["  archivos_template_(hashes)"] = len(templates)
        F["funciones_descartadas:corta"] = tot.get("fn_corta", 0)
        F["funciones_descartadas:anidada"] = tot.get("fn_anidada", 0)
        F["funciones_>=min_lineas"] = n_fn_total
        F["funciones_descartadas:template"] = n_fn_template
        F["funciones_finales"] = len(funcs)
        F["owners_con_funciones"] = funcs.owner.nunique()
        F["lineas_py_no_vacias_por_repo_mediana"] = int(rdf.py_nonblank_all.median())
        F["repos_<2k_lineas_reales"] = int((rdf.py_nonblank_all < cfg["selection"]["min_py_lines"]).sum())
